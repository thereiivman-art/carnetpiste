const { chromium, BASE } = require('../lib');
(async () => {
  const lang = process.argv[2] || 'fr';
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 380, height: 900 }, deviceScaleFactor: 2 });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto(BASE + 'index.html#lang=' + lang + '&admin=1'); await p.waitForTimeout(1600);
  await p.click('#settings-toggle'); await p.waitForTimeout(300);
  await p.getByText(lang === 'fr' ? 'Aide' : 'Help', { exact: true }).first().click(); await p.waitForTimeout(300);
  await p.click('[data-pill-group="aide"][data-pill="admin"]'); await p.waitForTimeout(500);
  await p.click('[data-action="evimp-check"]'); await p.waitForTimeout(300);
  await p.click('[data-action="evimp-go"]'); await p.waitForTimeout(800);
  await p.click('.bottom-nav-btn[data-view^="carnet"]'); await p.waitForTimeout(500);
  await p.click('.subnav-btn[data-view="budget"]'); await p.waitForTimeout(500);
  console.log('seasons:', await p.$$eval('.budget-season', e => e.map(x => x.innerText.replace(/\n/g, ' ')).join(' | ')));
  await p.click('[data-budget-season="2027"]'); await p.waitForTimeout(400);
  await p.click('[data-pill-group="budget"][data-pill="others"]'); await p.waitForTimeout(300);
  const ids = await p.$$eval('.budget-row', rs => rs.map(r => [r.getAttribute('data-row'), r.querySelector('strong').textContent]));
  const id = n => ids.find(x => new RegExp(n).test(x[1]))[0];
  for (const n of ['Portim', 'Jerez', 'Mugello', 'Le Mans']) await p.click('#bud-' + id(n) + '-on');
  await p.click('[data-pill-group="budget"][data-pill="mine"]'); await p.waitForTimeout(300);
  const port = id('Portim');
  await p.click('[data-row="' + port + '"] summary');
  await p.fill('#bud-' + port + '-travel', '320'); await p.fill('#bud-' + port + '-hotel', '400'); await p.fill('#bud-' + port + '-tyres', '450');
  await p.click('[data-row="' + port + '"] [data-budget-act="add-line"]'); await p.waitForTimeout(300);
  await p.keyboard.type('Ferry'); await p.fill('[data-row="' + port + '"] [data-f="amount"]', '90');
  await p.click('.budget-extras-card [data-budget-act="add-line"]'); await p.waitForTimeout(300);
  await p.keyboard.type(lang === 'fr' ? 'Combinaison' : 'Leathers'); await p.fill('.budget-extras-card [data-f="amount"]', '650');
  await p.waitForTimeout(900);
  console.log('hero:', (await p.$eval('.budget-hero', e => e.innerText)).replace(/\n/g, ' | '));
  console.log('kpis:', (await p.$eval('.budget-kpis', e => e.innerText)).replace(/\n/g, ' | '));
  console.log('split:', (await p.$eval('.budget-split', e => e.innerText)).replace(/\n/g, ' | '));
  await p.evaluate(() => window.scrollTo(0, 0));
  await p.screenshot({ path: 'b4-2027-' + lang + '.png', fullPage: true });
  await p.click('[data-budget-season="2026"]'); await p.waitForTimeout(400);
  await p.click('[data-row="e2"] summary'); await p.fill('#bud-e2-travel', '200'); await p.waitForTimeout(800);
  console.log('2026 hero:', (await p.$eval('.budget-hero', e => e.innerText)).replace(/\n/g, ' | '));
  await p.evaluate(() => window.scrollTo(0, 0));
  await p.screenshot({ path: 'b4-2026-' + lang + '.png', fullPage: true });
  console.log('errs', JSON.stringify(errs)); await b.close();
})();
